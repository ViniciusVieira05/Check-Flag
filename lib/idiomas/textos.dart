String tr(String key, [Map<String, String> params = const {}]) {
  final lang = SettingsService.instance.language;
  String text = _texts[lang]?[key] ?? _texts['pt']![key] ?? key;

  params.forEach((name, value) {
    text = text.replaceAll('{$name}', value);
  });
  return text;
}

String continentName(Continent c) => tr('continent.${c.jsonKey}');

String modeLabel(String? continentKey) {
  if (continentKey == null) return tr('world');
  return tr('continent.$continentKey');
}

String difficultyLabel(String difficulty) => tr(difficulty == 'hard' ? 'hard' : 'easy');

String timeLabel(int seconds) => seconds < 120 ? '${seconds}s' : '${seconds ~/ 60} min';

